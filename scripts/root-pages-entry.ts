import { readFile, writeFile, readdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { root } from './load-content';

// The repository root serves the real game; assets remain in the compact publishing folder.
const compiled = await readFile(resolve(root, 'github-pages/index.html'), 'utf8');
if (!compiled.includes('<head>') || compiled.includes('<base '))
  throw Error('Unexpected compiled entry');
await writeFile(
  resolve(root, 'index.html'),
  compiled.replace('<head>', '<head><base href="./github-pages/">')
);

// Branch-based GitHub Pages uses Jekyll. Exclude source/original art so publishing stays below 1 GB.
const names = (await readdir(root))
  .filter((n) => !n.startsWith('.') && !['index.html', 'github-pages', '_config.yml'].includes(n))
  .sort();
await writeFile(
  resolve(root, '_config.yml'),
  await format(
    '# Generated by npm run build:pages. Publish only the root entry and compact game folder.\n' +
      'exclude:\n' +
      names.map((n) => `  - ${JSON.stringify(n)}`).join('\n') +
      '\n',
    { ...(await resolveConfig(resolve(root, '_config.yml'))), parser: 'yaml' }
  )
);
console.log(
  'Root entry ready: index.html → github-pages assets; original art excluded from branch publishing.'
);
